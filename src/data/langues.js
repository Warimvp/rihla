// Jointure concepts ↔ mots : chaque mot porte {id, fr, ar, t, r?}.
export const LANGUES = BRUTES.map((langue) => ({
  ...langue,
  lecons: LECONS_META.map((meta) => ({
    ...meta,
    mots: langue.mots[meta.id].map((mot, i) => ({ ...CONCEPTS[meta.id][i], ...mot })),
  })),
}))

export const langueParId = (id) => LANGUES.find((l) => l.id === id)

export const nomLangue = (langue, locale) => (locale === 'ar' ? langue.nomAr : langue.nomFr)
export const nomVille = (langue, locale) => (locale === 'ar' ? langue.villeAr : langue.ville)
export const titreLecon = (lecon, locale) => (locale === 'ar' ? lecon.titreAr : lecon.titreFr)
export const histoire = (langue, locale) => (locale === 'ar' ? langue.histAr : langue.histFr)
